/* global console, URL */
// Regenerates the emoji catalog from emojibase-data (a dev-only dependency).
// Writes one entrypoints/inputview/emoji/categories/<id>.ts per category
// (skin flags included) and catalog.ts, which assembles them.
// Run: node scripts/gen-emoji.mjs
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL('..', import.meta.url));
const en = require('emojibase-data/en/data.json');
const subgroupName = require('emojibase-data/meta/groups.json').subgroups;

// Skip emoji newer than this Unicode Emoji version — older devices render them
// as tofu. Bump once the fleet's emoji font is known to be newer.
const kMaxVersion = 15.1;

// Category tabs (id + tab icon), in display order. Each emojibase emoji maps to
// exactly one via its group/subgroup.
const CATS = [
  { id: 'smileys', icon: '😀' },
  { id: 'gestures', icon: '👍' },
  { id: 'people', icon: '🧑' },
  { id: 'hearts', icon: '❤️' },
  { id: 'animals', icon: '🐱' },
  { id: 'food', icon: '🍜' },
  { id: 'activities', icon: '⚽' },
  { id: 'travel', icon: '🚗' },
  { id: 'objects', icon: '💡' },
  { id: 'symbols', icon: '🔣' },
  { id: 'flags', icon: '🚩' },
];

function catFor(it) {
  const sg = subgroupName[it.subgroup] ?? '';
  switch (it.group) {
    case 0: return sg === 'heart' ? 'hearts' : 'smileys';
    case 1: return /^hand|^body-parts$/.test(sg) ? 'gestures' : 'people';
    case 3: return 'animals';
    case 4: return 'food';
    case 5: return 'travel';
    case 6: return 'activities';
    case 7: return 'objects';
    case 8: return 'symbols';
    case 9: return 'flags';
    default: return null; // component / unknown
  }
}

const buckets = Object.fromEntries(CATS.map(c => [c.id, []]));
let count = 0;
for (const it of en) {
  const cat = catFor(it);
  if (!cat || it.version > kMaxVersion) continue;
  buckets[cat].push({ char: it.emoji, order: it.order ?? 1e9, skin: Array.isArray(it.skins) && it.skins.length > 0 });
  count++;
}

const kHeader = '// AUTO-GENERATED by scripts/gen-emoji.mjs — do not edit by hand.\n';

mkdirSync(root + 'entrypoints/inputview/emoji/categories', { recursive: true });
for (const c of CATS) {
  const entries = buckets[c.id].sort((a, b) => a.order - b.order);
  const items = entries.map(x => (x.skin ? `s(${JSON.stringify(x.char)})` : `e(${JSON.stringify(x.char)})`));
  const lines = [];
  for (let i = 0; i < items.length; i += 8) {
    lines.push(`    ${items.slice(i, i + 8).join(', ')},`);
  }
  // Only the helpers the file uses, or the all-plain files trip no-unused-vars.
  const helpers
    = (entries.some(x => !x.skin) ? 'const e = (char: string): EmojiDef => ({ char });\n' : '')
      + (entries.some(x => x.skin) ? 'const s = (char: string): EmojiDef => ({ char, skin: true });\n' : '');
  const body = kHeader
    + 'import type { EmojiDef } from \'../data\';\n\n' + helpers
    + `\nexport const ${c.id}: EmojiDef[] = [\n${lines.join('\n')}\n];\n`;
  writeFileSync(root + `entrypoints/inputview/emoji/categories/${c.id}.ts`, body);
}

const catalog = kHeader
  + 'import type { EmojiCategory } from \'./data\';\n'
  + CATS.map(c => `import { ${c.id} } from './categories/${c.id}';\n`).join('')
  + '\nexport const kEmojiCategories: EmojiCategory[] = [\n'
  + CATS.map(c => `    { id: ${JSON.stringify(c.id)}, icon: ${JSON.stringify(c.icon)}, emoji: ${c.id} },\n`).join('')
  + '];\n';
writeFileSync(root + 'entrypoints/inputview/emoji/catalog.ts', catalog);

console.log(`catalog: ${count} emoji across ${CATS.length} categories`);
for (const c of CATS) console.log(`  ${c.id}: ${buckets[c.id].length}`);
